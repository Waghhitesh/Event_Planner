"use client";

/**
 * @file components/dashboard/GoogleActions.tsx
 * @description Google Calendar and Google Sheets integration action bar.
 */

import { memo, useMemo, useCallback } from "react";
import { Calendar, Download, ExternalLink, Printer } from "lucide-react";
import {
  generateGoogleCalendarUrl,
  generateGoogleSheetsCsv,
  slugifyFilename,
} from "@/lib/google-integrations";
import type { GeminiResponse, Currency } from "@/lib/schemas";
import { Button, LinkButton } from "@/components/ui";

interface GoogleActionsProps {
  plan: GeminiResponse;
  eventDate: string;
  location: string;
  currency?: Currency;
}

/**
 * Renders the Google Calendar sync link and Google Sheets CSV export button.
 */
const GoogleActions = memo(function GoogleActions({
  plan,
  eventDate,
  location,
  currency = "INR",
}: GoogleActionsProps) {
  const calendarUrl = useMemo(
    () =>
      generateGoogleCalendarUrl(
        plan.eventName,
        eventDate,
        `${plan.themeSummary}\n\nGenerated by EventPulse AI`,
        location
      ),
    [plan.eventName, plan.themeSummary, eventDate, location]
  );

  const handleExportCsv = useCallback(() => {
    const csv = generateGoogleSheetsCsv(plan, currency);
    const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${slugifyFilename(plan.eventName)}_EventPulse_Plan.csv`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }, [plan, currency]);

  const handlePrint = useCallback(() => {
    window.print();
  }, []);

  return (
    <div className="flex flex-wrap gap-3" role="group" aria-label="Export and integration actions">
      {/* Google Calendar */}
      <LinkButton href={calendarUrl} target="_blank" rel="noopener noreferrer" variant="secondary">
        <Calendar className="h-4 w-4" aria-hidden="true" />
        Sync with Google Calendar <span className="sr-only">(opens in new tab)</span>
        <ExternalLink className="h-3 w-3 opacity-60" aria-hidden="true" />
      </LinkButton>

      {/* Google Sheets CSV */}
      <Button variant="secondary" onClick={handleExportCsv}>
        <Download className="h-4 w-4" aria-hidden="true" />
        Export to Google Sheets (.csv)
      </Button>

      {/* Print / Save as PDF */}
      <Button variant="secondary" onClick={handlePrint}>
        <Printer className="h-4 w-4" aria-hidden="true" />
        Print / Save as PDF
      </Button>
    </div>
  );
});

export default GoogleActions;
